void rotation_x(float x, float y, float z, float angle, float* out_x, float* out_y, float* out_z) {
    *out_x = x;
    *out_y = y * cos(angle) - z * sin(angle);
    *out_z = y * sin(angle) + z * cos(angle);
}

void rotation_y(float x, float y, float z, float angle, float* out_x, float* out_y, float* out_z) {
    *out_x = x * cos(angle) + z * sin(angle);
    *out_y = y;
    *out_z = -x * sin(angle) + z * cos(angle);
}

void rotation_z(float x, float y, float z, float angle, float* out_x, float* out_y, float* out_z) {
    *out_x = x * cos(angle) - y * sin(angle);
    *out_y = x * sin(angle) + y * cos(angle);
    *out_z = z;
}

