void project_vertex(float x3d, float y3d, float z3d, float offset_z, int* out_x, int* out_y) { 
    float d = 100.0;        

    float z = z3d + offset_z;
    if (z < 1.0) z = 1.0;

    float projected_x = (x3d * d) / z;
    float projected_y = (y3d * d) / z;

    *out_x = (int)(projected_x * 2) + (WIDTH / 2);
    *out_y = (int)projected_y + (HEIGHT / 2);
}

